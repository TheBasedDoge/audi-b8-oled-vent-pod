#!/usr/bin/env python3
"""Generate firmware/S5GaugePod_Test/gauge_fonts.h from TTF files.

Glyphs are rendered with FreeType (via Pillow) at the exact pixel size used on
screen and stored as 4-bit alpha, so text is anti-aliased on the AMOLED and in
the browser preview alike (the preview runs the same renderer compiled to wasm).

usage: python3 tools/gen_fonts.py <font dir> <output .h> [barlow|audi]
  barlow (default): Barlow Light / Regular / Medium / SemiBold from github.com/google/fonts
                    (SIL Open Font License: free to share). This is what the repository ships:
                    python3 tools/gen_fonts.py <barlow dir> firmware/S5GaugePod_Test/gauge_fonts.h
  audi   : AudiType-Normal_03.ttf / AudiType-Bold_03.ttf, if you have them. The font is marked
           "for exclusive use by AUDI AG", so it is never committed: write it to the private folder,
           which git ignores and the firmware prefers when it's there:
           python3 tools/gen_fonts.py <audi dir> firmware/S5GaugePod_Test/private/gauge_fonts.h audi

The font names in the firmware stay the same whichever family is used:
  R14..R40 = numerals, L50..L84 = large readouts, C12..C28 = labels and captions,
  C44 = the big words in pop-ups (capitals only).
Numerals are slanted like the cluster's (Audi Type has no italic, so the
upright glyphs are sheared by SLANT in FreeType, with proper anti-aliasing).
"""
import sys, os
from PIL import ImageFont
import freetype

SLANT = 0.19          # horizontal shear (about 11 degrees), numerals only

DIGITS = "0123456789.-− "
ASCII = "".join(chr(c) for c in range(32, 127)) + "°×−·"

# name, file, px size, charset
AUDI = [
    ("R14", "AudiType-Normal_03.ttf", 13, DIGITS),
    ("R24", "AudiType-Normal_03.ttf", 23, DIGITS),
    ("R28", "AudiType-Normal_03.ttf", 26, DIGITS + "\u00b0FCVpsiar:%"),
    ("R32", "AudiType-Normal_03.ttf", 30, DIGITS + "\u00b0FCVpsiar:%"),
    ("R40", "AudiType-Normal_03.ttf", 38, DIGITS + "\u00b0FVpsi%"),
    ("L50", "AudiType-Normal_03.ttf", 46, DIGITS),
    ("L56", "AudiType-Normal_03.ttf", 52, DIGITS),
    ("L84", "AudiType-Normal_03.ttf", 78, DIGITS),
    ("L70", "AudiType-Normal_03.ttf", 66, DIGITS + "\u00b0%"),
    ("C24", "AudiType-Bold_03.ttf", 22, ASCII),
    ("C44", "AudiType-Bold_03.ttf", 40, " ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.-:/?!%\u00b0"),
    ("C12", "AudiType-Normal_03.ttf", 11, ASCII),
    ("C13", "AudiType-Normal_03.ttf", 12, ASCII),
    ("C16", "AudiType-Bold_03.ttf", 14, ASCII),
    ("C20", "AudiType-Bold_03.ttf", 18, ASCII),
    ("C28", "AudiType-Bold_03.ttf", 26, ASCII),
]
BARLOW = [   # same names and characters as AUDI, sizes picked to match its cap heights (layouts are tuned to them)
    ("R14", "Barlow-Regular.ttf", 13, DIGITS),
    ("R24", "Barlow-Regular.ttf", 23, DIGITS),
    ("R28", "Barlow-Regular.ttf", 27, DIGITS + "\u00b0FCVpsiar:%"),
    ("R32", "Barlow-Regular.ttf", 31, DIGITS + "\u00b0FCVpsiar:%"),
    ("R40", "Barlow-Regular.ttf", 38, DIGITS + "\u00b0FVpsi%"),
    ("L50", "Barlow-Light.ttf", 48, DIGITS),
    ("L56", "Barlow-Light.ttf", 52, DIGITS),
    ("L84", "Barlow-Light.ttf", 81, DIGITS),
    ("L70", "Barlow-Light.ttf", 68, DIGITS + "\u00b0%"),
    ("C24", "Barlow-SemiBold.ttf", 22, ASCII),
    ("C44", "Barlow-SemiBold.ttf", 40, " ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.-:/?!%\u00b0"),
    ("C12", "Barlow-Medium.ttf", 11, ASCII),
    ("C13", "Barlow-Medium.ttf", 12, ASCII),
    ("C16", "Barlow-SemiBold.ttf", 14, ASCII),
    ("C20", "Barlow-SemiBold.ttf", 19, ASCII),
    ("C28", "Barlow-SemiBold.ttf", 26, ASCII),
]


def build(src_dir, FONTS):
    out = ["// Generated by tools/gen_fonts.py - do not edit.",
           "// 4-bit anti-aliased glyphs. Family: " + FAMILY,
           "#pragma once", "#include <stdint.h>", "",
           "struct GGlyph { uint16_t cp; uint8_t w, h; int8_t xo, yo; uint16_t adv64; uint32_t off; };",
           "struct GFont  { const GGlyph *g; uint16_t n; const uint8_t *bmp; uint8_t capH; };", ""]
    total = 0
    for name, fn, size, chars in FONTS:
        font = ImageFont.truetype(os.path.join(src_dir, fn), size)
        cap = -font.getbbox("0" if name[0] != "C" else "H", anchor="ls")[1]
        glyphs, nibbles = [], []
        slant = SLANT if name[0] != "C" else 0
        if slant:
            face = freetype.Face(os.path.join(src_dir, fn))
            face.set_pixel_sizes(0, size)
            m = freetype.Matrix(0x10000, int(slant * 0x10000), 0, 0x10000)
            # shift left by half the lean at mid cap height, so centred text stays centred
            face.set_transform(m, freetype.Vector(int(-slant * cap / 2 * 64), 0))
        for ch in sorted(set(chars), key=ord):
            if slant:
                face.load_char(ch, freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_NORMAL)
                gs, bm = face.glyph, face.glyph.bitmap
                adv = gs.advance.x / 64.0
                off = len(nibbles)
                for y in range(bm.rows):
                    for x in range(bm.width):
                        nibbles.append((bm.buffer[y * bm.pitch + x] * 15 + 127) // 255)
                glyphs.append((ord(ch), bm.width, bm.rows, gs.bitmap_left, -gs.bitmap_top, round(adv * 64), off))
                continue
            adv = font.getlength(ch)
            if ch == " ":
                glyphs.append((ord(ch), 0, 0, 0, 0, round(adv * 64), len(nibbles)))
                continue
            mask, (ox, oy) = font.getmask2(ch, mode="L", anchor="ls")
            w, h = mask.size
            off = len(nibbles)
            for y in range(h):
                for x in range(w):
                    nibbles.append((mask.getpixel((x, y)) * 15 + 127) // 255)
            glyphs.append((ord(ch), w, h, ox, oy, round(adv * 64), off))
        if len(nibbles) % 2:
            nibbles.append(0)
        data = bytes((nibbles[i] << 4) | nibbles[i + 1] for i in range(0, len(nibbles), 2))
        total += len(data) + len(glyphs) * 12
        out.append(f"static const uint8_t {name}_bmp[] = {{")
        for i in range(0, len(data), 24):
            out.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        out.append("};")
        out.append(f"static const GGlyph {name}_g[] = {{")
        for g in glyphs:
            out.append("  {%d,%d,%d,%d,%d,%d,%d}," % g)
        out.append("};")
        out.append(f"static const GFont {name} = {{{name}_g, {len(glyphs)}, {name}_bmp, {cap}}};  // {fn} {size}px")
        out.append("")
    out.insert(2, f"// {total // 1024} KB of glyph data")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    src, dst = sys.argv[1], sys.argv[2]
    FAMILY = sys.argv[3] if len(sys.argv) > 3 else "barlow"
    with open(dst, "w") as f:
        f.write(build(src, AUDI if FAMILY == "audi" else BARLOW))
    print("wrote", dst)
