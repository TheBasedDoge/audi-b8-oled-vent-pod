#!/usr/bin/env python3
"""Generate the boot-screen badge header from a PNG with transparency.

The badge is pre-scaled (with proper alpha) to each size the screens use and
stored as RGB565 plus 8-bit alpha, so it blends cleanly onto the gauge faces.
usage: python3 tools/gen_badge.py docs/art/pod-badge.png firmware/S5GaugePod_Test/gauge_badge.h
  The repository ships the original gauge badge above. To use your own (say, your car's badge, which
  is someone else's trademark and so not committed), write it to the private folder, which git ignores
  and the firmware prefers when it's there:
  python3 tools/gen_badge.py my-badge.png firmware/S5GaugePod_Test/private/gauge_badge.h
"""
import sys, os
from PIL import Image

SIZES = [("BADGE_SPLASH", 300), ("BADGE_FACE", 64)]   # name, width in px

def build(src):
    im = Image.open(src).convert("RGBA")
    bbox = im.getbbox()                       # trim transparent margins
    im = im.crop(bbox)
    out = ["// Generated by tools/gen_badge.py from " + os.path.basename(src) + " - do not edit.",
           "#pragma once", "#include <stdint.h>", "",
           "struct GImage { uint16_t w, h; const uint16_t *rgb; const uint8_t *a; };", ""]
    for name, w in SIZES:
        h = round(im.height * w / im.width)
        s = im.convert("RGBa").resize((w, h), Image.LANCZOS).convert("RGBA")
        rgb, a = [], []
        px = s.tobytes()
        for i in range(0, len(px), 4):
            r, g, b, al = px[i], px[i + 1], px[i + 2], px[i + 3]
            rgb.append(((r * 31 + 127) // 255) << 11 | ((g * 63 + 127) // 255) << 5 | ((b * 31 + 127) // 255))
            a.append(al)
        out.append(f"static const uint16_t {name}_rgb[] = {{")
        for i in range(0, len(rgb), 16):
            out.append("  " + ",".join("0x%04X" % v for v in rgb[i:i + 16]) + ",")
        out.append("};")
        out.append(f"static const uint8_t {name}_a[] = {{")
        for i in range(0, len(a), 32):
            out.append("  " + ",".join(str(v) for v in a[i:i + 32]) + ",")
        out.append("};")
        out.append(f"static const GImage {name} = {{{w}, {h}, {name}_rgb, {name}_a}};")
        out.append("")
    return "\n".join(out) + "\n"

if __name__ == "__main__":
    open(sys.argv[2], "w").write(build(sys.argv[1]))
    print("wrote", sys.argv[2])
