#!/usr/bin/env python3
"""Gzip tools/web/index.html into firmware/S5GaugePod_Test/web_page.h (served as-is by the pod).
usage: python3 tools/gen_web.py"""
import gzip, os
here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, "web", "index.html")
dst = os.path.join(here, "..", "firmware", "S5GaugePod_Test", "web_page.h")
data = gzip.compress(open(src, "rb").read(), 9, mtime=0)
with open(dst, "w") as f:
    f.write("// Generated by tools/gen_web.py from tools/web/index.html - do not edit.\n#pragma once\n#include <stdint.h>\n")
    f.write(f"static const uint32_t WEB_PAGE_GZ_LEN = {len(data)};\nstatic const uint8_t WEB_PAGE_GZ[] = {{\n")
    for i in range(0, len(data), 24):
        f.write("  " + ",".join(str(b) for b in data[i:i + 24]) + ",\n")
    f.write("};\n")
print(f"wrote {dst} ({len(data)} bytes gzipped)")
